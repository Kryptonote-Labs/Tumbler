<script lang="ts">
  import { onDestroy, tick, type Snippet } from 'svelte';
  import type { PresentationDocument, PresentationSlide } from '@tumblerjs/slides';
  import PresentationSlideView from './PresentationSlideView.svelte';
  let {
    presentation,
    indicator,
    onreorder,
    index = $bindable(0),
  }: {
    presentation: PresentationDocument;
    index?: number;
    indicator?: Snippet<[PresentationSlide]>;
    onreorder?: (slideId: string, index: number) => void;
  } = $props();
  let rail = $state<HTMLElement>();
  let visible = $state<Record<string, boolean>>({});
  let rendered = $state<Record<string, boolean>>({});
  let frame = 0;
  let pending:
    | { id: string; x: number; y: number; pointerId: number; node: HTMLButtonElement }
    | undefined;
  let drag = $state<{ id: string; x: number; y: number; width: number }>();
  let slot = $state(0);
  let line = $state(0);
  let announcement = $state('');
  let scrollFrame = 0;
  let suppressClick = false;
  const draggedSlide = $derived(presentation.slides.find((slide) => slide.id === drag?.id));

  function updateDrop() {
    const moving = drag;
    if (!rail || !moving) return;
    const buttons = [...rail.querySelectorAll<HTMLButtonElement>('button[data-index]')];
    const next = buttons.findIndex((button) => {
      const bounds = button.getBoundingClientRect();
      return moving.y < bounds.top + bounds.height / 2;
    });
    slot = next < 0 ? buttons.length : next;
    const target = buttons[slot];
    const last = buttons.at(-1);
    line = target ? target.offsetTop - 5 : last ? last.offsetTop + last.offsetHeight + 5 : 0;
  }
  function autoScroll() {
    if (!rail || !drag) return;
    const bounds = rail.getBoundingClientRect();
    const speed = drag.y < bounds.top + 40 ? -9 : drag.y > bounds.bottom - 40 ? 9 : 0;
    if (speed) rail.scrollTop += speed;
    updateDrop();
    scrollFrame = requestAnimationFrame(autoScroll);
  }
  function startPointer(event: PointerEvent, id: string) {
    if (!onreorder || event.button !== 0 || !event.isPrimary) return;
    // Touch swipes on the preview scroll the rail. Only the number/grip starts a touch drag.
    if (
      event.pointerType === 'touch' &&
      !(event.target instanceof Element && event.target.closest('.number'))
    )
      return;
    const node = event.currentTarget as HTMLButtonElement;
    pending = { id, x: event.clientX, y: event.clientY, pointerId: event.pointerId, node };
    node.setPointerCapture(event.pointerId);
  }
  function movePointer(event: PointerEvent) {
    if (!pending || event.pointerId !== pending.pointerId) return;
    if (!drag && Math.hypot(event.clientX - pending.x, event.clientY - pending.y) < 6) return;
    event.preventDefault();
    const starting = !drag;
    drag = { id: pending.id, x: event.clientX, y: event.clientY, width: pending.node.offsetWidth };
    suppressClick = true;
    updateDrop();
    if (starting) autoScroll();
  }
  function cancelDrag() {
    if (pending?.node.hasPointerCapture(pending.pointerId))
      pending.node.releasePointerCapture(pending.pointerId);
    pending = undefined;
    drag = undefined;
    cancelAnimationFrame(scrollFrame);
    // The click generated by pointerup must not select a different slide.
    setTimeout(() => {
      suppressClick = false;
    }, 0);
  }
  function finishPointer(event: PointerEvent) {
    if (!pending || event.pointerId !== pending.pointerId) return;
    if (drag && rail) {
      const bounds = rail.getBoundingClientRect();
      const from = presentation.slides.findIndex((slide) => slide.id === drag?.id);
      const to = slot > from ? slot - 1 : slot;
      if (
        event.clientX >= bounds.left &&
        event.clientX <= bounds.right &&
        event.clientY >= bounds.top &&
        event.clientY <= bounds.bottom &&
        from >= 0 &&
        to !== from
      ) {
        onreorder?.(drag.id, to);
        announcement = `Slide moved to position ${to + 1}`;
      }
    }
    cancelDrag();
  }
  onDestroy(() => {
    if (typeof cancelAnimationFrame !== 'undefined') cancelAnimationFrame(scrollFrame);
  });

  // Mount one nearby preview per frame so a scroll jump does not build a row
  // of full slide renderers in one task. The selected slide renders immediately.
  function revealNext() {
    frame = 0;
    const next = Object.keys(visible).find((id) => visible[id] && !rendered[id]);
    if (!next) return;
    rendered[next] = true;
    frame = requestAnimationFrame(revealNext);
  }
  onDestroy(() => {
    if (typeof cancelAnimationFrame !== 'undefined') cancelAnimationFrame(frame);
  });
  function observe(node: HTMLElement, id: string) {
    const observer = new IntersectionObserver(
      (entries) => {
        visible[id] = entries[0]?.isIntersecting ?? false;
        if (!visible[id]) rendered[id] = false;
        else if (!frame) frame = requestAnimationFrame(revealNext);
      },
      { root: rail, rootMargin: '160px' },
    );
    observer.observe(node);
    return {
      destroy() {
        observer.disconnect();
        delete visible[id];
        delete rendered[id];
      },
    };
  }
  $effect(() => {
    const active = index;
    void tick().then(() => {
      const button = rail?.querySelector<HTMLButtonElement>(`button[data-index="${active}"]`);
      if (!button || !rail) return;
      if (button.offsetTop < rail.scrollTop) rail.scrollTop = button.offsetTop;
      else if (button.offsetTop + button.offsetHeight > rail.scrollTop + rail.clientHeight)
        rail.scrollTop = button.offsetTop + button.offsetHeight - rail.clientHeight;
    });
  });
  async function navigate(event: KeyboardEvent, current: number) {
    const last = presentation.slides.length - 1;
    if (event.altKey && onreorder && (event.key === 'ArrowUp' || event.key === 'ArrowDown')) {
      event.preventDefault();
      event.stopPropagation();
      const next = Math.max(0, Math.min(last, current + (event.key === 'ArrowUp' ? -1 : 1)));
      const id = presentation.slides[current]?.id;
      if (id && next !== current) {
        onreorder(id, next);
        announcement = `Slide moved to position ${next + 1}`;
        await tick();
        rail?.querySelector<HTMLButtonElement>(`button[data-index="${next}"]`)?.focus();
      }
      return;
    }
    const next =
      event.key === 'ArrowDown' || event.key === 'ArrowRight'
        ? Math.min(last, current + 1)
        : event.key === 'ArrowUp' || event.key === 'ArrowLeft'
          ? Math.max(0, current - 1)
          : event.key === 'Home'
            ? 0
            : event.key === 'End'
              ? last
              : undefined;
    if (next === undefined) return;
    event.preventDefault();
    index = next;
    await tick();
    rail
      ?.querySelector<HTMLButtonElement>(`button[data-index="${next}"]`)
      ?.focus({ preventScroll: true });
  }
</script>

<svelte:window
  onpointermove={movePointer}
  onpointerup={finishPointer}
  onpointercancel={cancelDrag}
  onblur={cancelDrag}
  onkeydown={(event) => {
    if (event.key === 'Escape' && drag) {
      event.preventDefault();
      event.stopPropagation();
      cancelDrag();
    }
  }}
/>
<span class="sr-only" aria-live="polite">{announcement}</span>
<nav class="slide-rail" aria-label="Slides" bind:this={rail}>
  {#each presentation.slides as slide, i (slide.id)}
    <button
      data-index={i}
      class:active={index === i}
      class:reorderable={!!onreorder}
      class:dragging={drag?.id === slide.id}
      onpointerdown={(event) => startPointer(event, slide.id)}
      ondragstart={(event) => event.preventDefault()}
      title={onreorder ? 'Drag to reorder · Alt + ↑ / ↓' : undefined}
      class:hidden={slide.hidden}
      aria-current={index === i ? 'true' : undefined}
      aria-label={`Slide ${i + 1}: ${slide.title}${slide.hidden ? ' (hidden)' : ''}`}
      tabindex={index === i ? 0 : -1}
      onclick={() => {
        if (!suppressClick) index = i;
      }}
      onkeydown={(event) => navigate(event, i)}
    >
      <span class="number">
        {i + 1}
        {#if slide.hidden}
          <svg
            class="hidden-icon"
            xmlns="http://www.w3.org/2000/svg"
            width="11"
            height="11"
            viewBox="0 0 24 24"
            fill="none"
            stroke="currentColor"
            stroke-width="1.75"
            stroke-linecap="round"
            stroke-linejoin="round"
            aria-hidden="true"
          >
            <path d="m3 3 18 18M10.6 10.6a2 2 0 0 0 2.8 2.8" />
            <path d="M9.9 5.2A10.8 10.8 0 0 1 12 5c7 0 10 7 10 7a16.8 16.8 0 0 1-3 4M6.5 6.5A18.4 18.4 0 0 0 2 12s3 7 10 7a10.8 10.8 0 0 0 5.5-1.5" />
          </svg>
        {/if}
      </span>
      <span
        class="preview"
        aria-hidden="true"
        inert
        use:observe={slide.id}
        style:aspect-ratio={`${presentation.width}/${presentation.height}`}
      >
        <span class="preview-surface"
          >{#if rendered[slide.id] || index === i}<PresentationSlideView
              {presentation}
              {slide}
              thumbnail
            />{/if}</span
        >
      </span>
      {#if indicator}<span class="indicator">{@render indicator(slide)}</span>{/if}
    </button>
  {/each}
  {#if drag}<span class="drop-line" style:top={`${line}px`} aria-hidden="true"></span>{/if}
</nav>
{#if drag && draggedSlide}
  <div
    class="drag-preview"
    aria-hidden="true"
    style:left={`${drag.x + 14}px`}
    style:top={`${drag.y + 12}px`}
    style:width={`${drag.width - 26}px`}
    style:aspect-ratio={`${presentation.width}/${presentation.height}`}
  >
    <PresentationSlideView {presentation} slide={draggedSlide} thumbnail />
  </div>
{/if}

