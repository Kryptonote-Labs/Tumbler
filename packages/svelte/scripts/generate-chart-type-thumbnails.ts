import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'svelte/compiler';

const directory = await mkdtemp(join(tmpdir(), 'tumbler-chart-thumbnails-'));
try {
  const built = await Bun.build({
    entrypoints: [fileURLToPath(new URL('./chart-type-thumbnails-entry.ts', import.meta.url))],
    target: 'bun',
    outdir: directory,
    plugins: [
      {
        name: 'chart-thumbnail-renderer',
        setup(build) {
          build.onLoad({ filter: /\.svelte$/ }, async ({ path }) => ({
            contents: compile(await Bun.file(path).text(), {
              filename: path,
              generate: 'server',
              dev: false,
            }).js.code,
            loader: 'js',
          }));
        },
      },
    ],
  });
  if (!built.success)
    throw new AggregateError(built.logs, 'Could not compile the thumbnail renderer.');
  const { thumbnails } = (await import(
    join(directory, 'chart-type-thumbnails-entry.js')
  )) as typeof import('./chart-type-thumbnails-entry.ts');
  const images = thumbnails();
  const entries = [];
  for (const image of images) {
    await Bun.write(
      new URL(`../src/chart-type-thumbnails/${image.name}.svg`, import.meta.url),
      image.svg + '\n',
    );
    entries.push(
      `  ${JSON.stringify(image.key)}: new URL('./chart-type-thumbnails/${image.name}.svg', import.meta.url).href,`,
    );
  }
  await Bun.write(
    new URL('../src/chart-type-thumbnails.ts', import.meta.url),
    `// Generated by scripts/generate-chart-type-thumbnails.ts.\nexport const chartTypeThumbnails: Readonly<Record<string, string>> = {\n${entries.join('\n')}\n};\n`,
  );
  console.log(`Generated ${images.length} chart type thumbnails.`);
} finally {
  await rm(directory, { recursive: true, force: true });
}
