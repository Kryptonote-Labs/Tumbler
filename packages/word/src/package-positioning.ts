import type { LosslessXmlElement } from '@tumblerjs/ooxml';
import type { PackageXml } from './package-xml.ts';

const indentNames = new Set(['left', 'right', 'start', 'end', 'firstLine', 'hanging', 'leftChars', 'rightChars', 'startChars', 'endChars', 'firstLineChars', 'hangingChars']);

/** Reset direct positioning, keeping extension markup even when new positioning is supplied. */
export function resetPositioningMarkup(markup: PackageXml, element: LosslessXmlElement | undefined, name: 'ind' | 'tabs', replacement = ''): string {
  if (!element) return replacement;
  const attributes = element.attributes.filter(attribute => attribute.qualified !== 'xmlns:w' && !(name === 'ind' && attribute.namespaceUri === element.namespaceUri && indentNames.has(attribute.localName)));
  const children = element.children.filter(child => !(name === 'tabs' && child.kind === 'element' && child.namespaceUri === element.namespaceUri && child.localName === 'tab'));
  if (!replacement && !attributes.some(attribute => attribute.prefix !== 'xmlns') && !children.length) return '';
  // Replacement fragments are generated by paragraphPositioningXml, always using the w prefix.
  const freshAttributes = name === 'ind' ? replacement.match(/^<w:ind\b([^>]*?)\/>$/)?.[1] ?? '' : '';
  const freshChildren = name === 'tabs' ? replacement.replace(/^<w:tabs>/, '').replace(/<\/w:tabs>$/, '') : '';
  const source = markup.document.source.source;
  return `<w:${name} xmlns:w="${element.namespaceUri}"${attributes.map(attribute => ` ${source.slice(attribute.span.start, attribute.span.end)}`).join('')}${freshAttributes}>${children.map(child => markup.raw(child)).join('')}${freshChildren}</w:${name}>`;
}
