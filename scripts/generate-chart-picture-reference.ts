import { readdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { readChartContent } from '../packages/charts/src/index.ts';
import { createPresentation, openPresentationArtifact, applyPresentationCommand } from '../packages/slides/src/index.ts';

const input = resolve(process.argv[2] ?? 'compatibility-results/chart-resources/input');
const output = resolve(process.argv[3] ?? 'packages/charts/test/fixtures/chart-picture-reference.pptx');
const names = (await readdir(input)).filter(name => name.endsWith('.pptx')).sort();
let presentation = createPresentation();
for (const [index, name] of names.entries()) {
  const original = openPresentationArtifact(await Bun.file(resolve(input, name)).bytes());
  const part = original.document.package.parts.find(part => part.contentType === 'application/vnd.openxmlformats-officedocument.drawingml.chart+xml');
  if (!part) throw new Error(`Chart is missing in ${name}.`);
  if (index) presentation = applyPresentationCommand(presentation, { name: 'insert-slide', index });
  const slideId = presentation.document.slides[index]!.id;
  presentation = applyPresentationCommand(presentation, { name: 'insert-chart', slideId, bounds: { x: 80, y: 80, width: 480, height: 320 }, content: readChartContent(original.document.package, part.name) });
  presentation = applyPresentationCommand(presentation, { name: 'set-notes', slideId, notes: `${name}. Synthetic picture-fill reference. Generated by scripts/generate-chart-picture-reference.ts.` });
}
await Bun.write(output, presentation.bytes());
console.log(output);
