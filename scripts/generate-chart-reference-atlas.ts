import { resolve } from 'node:path';
import { OOXML_CHART_TYPES, CHART_BAR_SHAPES, createOoxmlChart, chartBytesToBase64, type CreateChartOptions } from '../packages/charts/src/index.ts';
import { createChartWorkbook } from '../packages/sheets/src/index.ts';
import { createPresentation, applyPresentationCommand } from '../packages/slides/src/index.ts';

const output = resolve(process.argv[2] ?? 'packages/charts/test/fixtures/chart-reference-atlas.pptx');
const plots: { readonly name: string; readonly options: Pick<CreateChartOptions, 'type' | 'shape' | 'grouping'> }[] = [
  ...OOXML_CHART_TYPES.map(type => ({ name: type, options: { type } })),
  ...CHART_BAR_SHAPES.map(shape => ({ name: `bar3DChart · ${shape}`, options: { type: 'bar3DChart' as const, shape, grouping: 'standard' as const } })),
];
let presentation = createPresentation();
for (const [index, plot] of plots.entries()) {
  if (index) presentation = applyPresentationCommand(presentation, { name: 'insert-slide', index });
  const source = createOoxmlChart({ ...plot.options, title: plot.name, categories: ['A', 'B', 'C'], series: Array.from({ length: 3 }, (_, index) => ({ name: `Series ${index + 1}`, values: [[8, 10, 9], [2, 3, 4], [5, 7, 6]][index]!, xValues: [1, 2, 3], bubbleSizes: [2, 4, 3] })) });
  const workbook = createChartWorkbook(source), slideId = presentation.document.slides[index]!.id;
  presentation = applyPresentationCommand(presentation, { name: 'insert-chart', slideId, bounds: { x: 80, y: 80, width: 480, height: 320 }, content: { xml: new TextDecoder().decode(workbook.source), workbook: chartBytesToBase64(workbook.artifact.bytes()) } });
  presentation = applyPresentationCommand(presentation, { name: 'set-notes', slideId, notes: `${plot.name}. Synthetic reference data. Native chart source and embedded workbook; no cached chart image. Generated by scripts/generate-chart-reference-atlas.ts.` });
}
await Bun.write(output, presentation.bytes());
console.log(output);
