<!-- A highlighted code block with an always-visible Copy button. `title` replaces the language label, e.g. a filename. -->
<script lang="ts">
  let { code, html, language = 'TypeScript', title }: { code: string; html: string; language?: string; title?: string } = $props();
  let status = $state<'idle' | 'copied' | 'failed'>('idle');
  let block: HTMLDivElement;
  async function copy() {
    try {
      await navigator.clipboard.writeText(code);
      status = 'copied';
    } catch {
      // Plain-HTTP origins have no clipboard API: select the code, then try the legacy copy command.
      const pre = block.querySelector('pre');
      if (pre) getSelection()?.selectAllChildren(pre);
      status = document.execCommand('copy') ? 'copied' : 'failed';
      if (status === 'copied') getSelection()?.removeAllRanges();
    }
    setTimeout(() => status = 'idle', 1600);
  }
</script>
<div class="code-block" bind:this={block}>
  <div class="code-caption">
    <span class:filename={title}>{title ?? language}</span>
    <button class="copy touch-target" onclick={copy} aria-label="Copy code">
      <svg width="13" height="13" viewBox="0 0 16 16" fill="none" stroke="currentColor" stroke-width="1.5" aria-hidden="true"><rect x="5.5" y="5.5" width="8" height="8" rx="1.5" /><path d="M10.5 3.5v-.5a1 1 0 0 0-1-1h-6a1 1 0 0 0-1 1v6a1 1 0 0 0 1 1h.5" /></svg>
      {status === 'failed' ? 'Selected, press Ctrl+C' : status === 'copied' ? 'Copied' : 'Copy'}
    </button>
  </div>
  <!-- HTML is escaped and generated by the server-side highlighter from authored examples. -->
  {@html html}
</div>
